export const getRandomReplacement = (word: string): string | null => {
  const replacements = allReplacements[word];
  if (!replacements || replacements.length === 0) return null;
  return replacements[Math.floor(Math.random() * replacements.length)];
};

export const hasReplacement = (word: string): boolean => {
  return !!allReplacements[word];
};

export const getReplacementCount = (): number => {
  return Object.keys(allReplacements).length;
};

